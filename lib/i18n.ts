// `translations` only covers the base i18n.ts namespaces. LanguageContext
// deep-merges in `extraTranslations` (lib/i18n-extra.ts, e.g. excursions.*,
// safaris.*, footer.newsletter*) at runtime, so a plain `typeof
// translations.en` under-describes what `t` actually contains once merged —
// TypeScript would flag real, working keys like `t.excursions.popular` as
// nonexistent. DeepPartialAny widens every nested object (but not arrays,
// e.g. `services`/`airports`) so merged-in keys type-check without losing
// autocomplete/literal typing for keys that already exist here.
type DeepPartialAny<T> = T extends readonly unknown[]
  ? T
  : T extends object
    ? { [K in keyof T]: DeepPartialAny<T[K]> } & Record<string, any>
    : T;

export type TranslationKeys = DeepPartialAny<typeof translations.en>;
